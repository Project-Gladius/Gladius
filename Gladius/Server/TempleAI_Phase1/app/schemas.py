import re
from enum import Enum

from pydantic import BaseModel, ConfigDict, Field, field_validator


class Emotion(str, Enum):
    NEUTRAL = "neutral"
    SORROWFUL = "sorrowful"
    BESTOW = "bestow"
    PLEASED = "pleased"
    UPSET = "upset"


class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


class TempleRequest(StrictModel):
    uid: str = Field(min_length=1, max_length=128)
    username: str = Field(min_length=1, max_length=100)
    message: str = Field(min_length=1, max_length=200)

    @field_validator("uid", "username", "message")
    @classmethod
    def strip_surrounding_whitespace(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("must not be blank")
        return value


class ModelReply(StrictModel):
    """Fields the AI is allowed to decide."""

    priority: int = Field(ge=0, le=100)
    responseText: str = Field(min_length=1, max_length=70)
    emotion: Emotion

    @field_validator("responseText")
    @classmethod
    def enforce_dialogue_format(cls, value: str) -> str:
        value = value.strip()
        sentence_count = len(re.findall(r"[.!?。！？]+", value))
        if sentence_count > 2:
            raise ValueError("responseText must contain at most two sentences")
        return value


class TempleResponse(ModelReply):
    """Public response. Identity is copied by the server, never generated by AI."""

    uid: str
    username: str


class HealthResponse(StrictModel):
    status: str
    aiConfigured: bool
